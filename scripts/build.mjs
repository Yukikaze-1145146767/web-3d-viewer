import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const bundled = await build({
    absWorkingDir: root,
    entryPoints: ['src/obj-worker.js'],
    bundle: true, format: 'iife', platform: 'browser', target: 'es2020',
    minify: true, legalComments: 'inline', write: false,
});
const template = await readFile(resolve(root, 'src/viewer.html'), 'utf8');
const marker = '__OBJ_WORKER_SOURCE__';
if (template.split(marker).length !== 2) throw new Error('Worker 构建标记必须恰好出现一次');
const license = await readFile(resolve(root, 'node_modules/three/LICENSE'), 'utf8');
const source = JSON.stringify(bundled.outputFiles[0].text).replace(/</g, '\\u003c');
const html = '<!-- Generated by npm run build from src/viewer.html and src/obj-worker.js. -->\n'
    + template.replace(marker, () => source) + '\n<!-- Bundled Three.js license:\n' + license + '\n-->\n';
const output = resolve(root, 'index.html');
if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')).replace(/\r\n/g, '\n') !== html.replace(/\r\n/g, '\n')) {
        throw new Error('index.html 与源码不一致，请运行 npm run build');
    }
} else {
    await writeFile(output, html);
}
console.log(`Single HTML: ${Buffer.byteLength(html)} bytes; worker: ${bundled.outputFiles[0].contents.length} bytes`);
